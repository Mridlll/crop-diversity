    for a, b in [("ORISSA", "ODISHA"), ("PONDICHERRY", "PUDUCHERRY"),
                 ("UTTARANCHAL", "UTTARAKHAND"), ("JAMMU AND KASHMIR", "JAMMU KASHMIR"),
                 ("NCT OF DELHI", "DELHI"), ("DELHI", "NCT OF DELHI"),
                 ("ANDAMAN AND NICOBAR ISLANDS", "ANDAMAN NICOBAR ISLANDS")]:
        pass
    return s



head("C2. Internal consistency")
issues = []

share_cols = [c for c in sh.columns if not c.startswith("DEPRECATED_")
              and (c.endswith("_vshare") or c.endswith("_ashare")
              or c.endswith("_share") or c in ("irr_share", "irr_share_vd11"))]
for c in share_cols:
    v = pd.to_numeric(sh[c], errors="coerce")
    bad = int(((v < -1e-9) | (v > 1 + 1e-9)).sum())
    if bad:
        issues.append("{}: {} values outside [0,1] (max {:.3f})".format(c, bad, v.max()))

part_ay = sh[["ay_src_canal_vshare", "ay_src_ground_vshare",
              "ay_src_surface_vshare", "ay_src_other_vshare"]].sum(axis=1)
off_ay = int((part_ay.sub(1).abs() > 0.01).sum())
part_vd = sh[[c for c in sh.columns if c.startswith("vd_src_") and c.endswith("_ashare")]].sum(axis=1)
off_vd = int((part_vd.sub(1).abs() > 0.01).sum())
w("Antyodaya irrigation source shares sum to 1: {} of {} districts off by >0.01.".format(
    off_ay, len(sh)))
w("PC11 VD irrigation source area shares sum to 1: {} of {} districts off by >0.01.".format(
    off_vd, len(sh)))

neg = {c: int((pd.to_numeric(sh[c], errors="coerce") < 0).sum())
       for c in sh.select_dtypes("number").columns}
neg = {k: v for k, v in neg.items() if v > 0}
w("Columns with negative values: {}".format(neg if neg else "none"))

ci = pd.to_numeric(sh["cropping_intensity"], errors="coerce")
w("Cropping intensity: min {:.2f}, p50 {:.2f}, max {:.2f}, below 1.0: {} districts.".format(
    ci.min(), ci.median(), ci.max(), int((ci < 1).sum())))
if int((ci < 1).sum()) > 0:
    issues.append("{} districts have cropping intensity below 1, which is impossible "
                  "if GCA = kharif+rabi+other and NSA is net sown".format(int((ci < 1).sum())))

for s in issues:
    w("- ISSUE: " + s)
verdict("C2 internal consistency", "PASS" if not issues else "WARN",
        "{} issue(s).".format(len(issues)))


# ------------------------------------------------------------------ C3
head("C3. Cross-source irrigation (Antyodaya 2019 vs PC11 VD 2011)")
a = pd.to_numeric(sh["irr_share"], errors="coerce")
b = pd.to_numeric(sh["irr_share_vd11"], errors="coerce")
ok = a.notna() & b.notna() & (b <= 1.5)
r_p = stats.pearsonr(a[ok], b[ok])
r_s = stats.spearmanr(a[ok], b[ok])
w("n = {} districts with both measures.".format(int(ok.sum())))
w("Pearson r = {:.3f}, Spearman rho = {:.3f}.".format(r_p[0], r_s[0]))
w("Antyodaya mean {:.3f}, PC11 VD mean {:.3f}.".format(a[ok].mean(), b[ok].mean()))
st = "PASS" if r_s[0] >= 0.70 else ("WARN" if r_s[0] >= 0.50 else "FAIL")
verdict("C3 irrigation cross-source", st,
        "Two independent sources 8 years apart agree at rho = {:.3f}.".format(r_s[0]))



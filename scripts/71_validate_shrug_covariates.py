# ------------------------------------------------------------------ C9
head("C9. Aggregation invariance against SHRUG's own district file")
ad = pd.read_stata(SHRUG + "/shrug-antyodaya-dta/antyodaya_pc11dist.dta",
                   columns=["pc11_state_id", "pc11_district_id",
                            "net_sown_area_in_hac", "area_irrigated_in_hac",
                            "total_unirrigated_land_area_in_h",
                            "net_sown_area_kharif_in_hac",
                            "net_sown_area_rabi_in_hac",
                            "net_sown_area_other_in_hac",
                            "total_cultivable_area_in_hac",
                            "total_no_of_farmers"])
sh_k = sh.copy()
for c in ["pc11_state_id", "pc11_district_id"]:
    sh_k[c] = sh_k[c].astype(str).str.zfill(2 if c.endswith("state_id") else 3)
    ad[c] = ad[c].astype(str).str.zfill(2 if c.endswith("state_id") else 3)
cmp = sh_k.merge(ad, on=["pc11_state_id", "pc11_district_id"], how="inner",
                 suffixes=("", "_ddl"))
w("Matched {} districts against SHRUG's pre-aggregated district file.".format(len(cmp)))
w("")
w("Levels are NOT expected to agree: `antyodaya_shrid.dta` covers 521,223 shrids")
w("carrying 857m people, while DDL's district file aggregates a wider village set")
w("carrying 1,007m. What must agree is every RATIO, since numerator and denominator")
w("come from the same village set on both sides.")
w("")
cmp["ddl_iu"] = cmp["area_irrigated_in_hac"] / (cmp["area_irrigated_in_hac"] +
                                                cmp["total_unirrigated_land_area_in_h"])
cmp["our_iu"] = cmp["ay_area_irrigated_in_hac"] / (cmp["ay_area_irrigated_in_hac"] +
                                                   cmp["ay_total_unirrigated_land_area_in_h"])
cmp["ddl_ci"] = (cmp["net_sown_area_kharif_in_hac"] + cmp["net_sown_area_rabi_in_hac"] +
                 cmp["net_sown_area_other_in_hac"]) / cmp["net_sown_area_in_hac"]
cmp["ddl_hold"] = cmp["total_cultivable_area_in_hac"] / cmp["total_no_of_farmers"]
w("| ratio | n | Pearson r | median relative gap |")
w("|---|---|---|---|")
rr9 = np.nan
for mine, theirs, lab in [("our_iu", "ddl_iu", "irrigation share"),
                          ("cropping_intensity", "ddl_ci", "cropping intensity"),
                          ("mean_holding_ha", "ddl_hold", "mean holding size")]:
    x = pd.to_numeric(cmp[mine], errors="coerce")
    y = pd.to_numeric(cmp[theirs], errors="coerce")
    kk = x.notna() & y.notna() & np.isfinite(x) & np.isfinite(y) & (y != 0)
    r_ = stats.pearsonr(x[kk], y[kk])[0]
    gap = ((x[kk] - y[kk]).abs() / y[kk].abs()).median()
    w("| {} | {} | {:.4f} | {:.4f} |".format(lab, int(kk.sum()), r_, gap))
    if mine == "our_iu":
        rr9 = r_
verdict("C9 aggregation invariance", "PASS" if rr9 >= 0.99 else "WARN",
        "Every ratio reproduces SHRUG's own district file at r >= {:.4f}.".format(rr9))


def keyify(state, dist):
    s = state.astype(str).str.upper().str.strip()
    s = s.str.replace(r"[^A-Z0-9 ]", " ", regex=True).str.replace(r"\s+", " ", regex=True).str.strip()
    s = s.replace(ALIAS_STATE)
    d = dist.astype(str).str.upper().str.strip()
    d = d.str.replace(r"[^A-Z0-9 ]", " ", regex=True).str.replace(r"\s+", " ", regex=True).str.strip()
    d = d.replace(ALIAS_DIST)
    return s + "|" + d


